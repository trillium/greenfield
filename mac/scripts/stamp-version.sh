#!/usr/bin/env bash
# Writes Sources/InserterCore/GeneratedVersion.swift (gitignored) from the git tags via ../scripts/version.sh,
# so the daemon's version is never typed in by hand (docs/versioning.md). Run by every make target that builds.
# The oldest app the daemon accepts is declared in mac/min-client-version.
# Without git history (a copy of mac/ alone) the committed copy of the stamped file travels with the copy.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="$here/Sources/InserterCore/GeneratedVersion.swift"
if [ -x "$here/../scripts/version.sh" ] && git -C "$here" rev-parse --git-dir >/dev/null 2>&1; then
  full="$("$here/../scripts/version.sh" --full)"
  marketing="$("$here/../scripts/version.sh" --marketing)"
  build="$("$here/../scripts/version.sh" --build)"
  commit="$(git -C "$here" rev-parse --short=7 HEAD 2>/dev/null || echo unknown)"
elif [ -f "$out" ]; then
  exit 0
else
  echo "error: no git history and no stamped GeneratedVersion.swift; stamp where the repository is and copy the file" >&2
  exit 1
fi
min="$(tr -d '[:space:]' < "$here/min-client-version")"
printf '%s' "$min" | grep -qE '^[0-9]+\.[0-9]+\.[0-9]+$' || { echo "error: min-client-version is not X.Y.Z" >&2; exit 1; }
tmp="$(mktemp)"
cat > "$tmp" <<SWIFT
// Generated by scripts/stamp-version.sh from git tags. Gitignored; never hand-edit.
enum StampedBuild {
    static let version = "$marketing"
    static let fullVersion = "$full"
    static let build = "$build"
    static let commit = "$commit"
    static let minClientVersion = "$min"
}
SWIFT
if ! cmp -s "$tmp" "$out" 2>/dev/null; then mv "$tmp" "$out"; else rm -f "$tmp"; fi
