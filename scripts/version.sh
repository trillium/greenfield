#!/usr/bin/env bash
# Derive the app version from git tags vX.Y.Z (docs/versioning.md). Bash 3.2 compatible.
# Usage: version.sh                 xcconfig lines: MARKETING_VERSION and CURRENT_PROJECT_VERSION
#        version.sh --marketing     numeric x.y.z for Apple (CFBundleShortVersionString)
#        version.sh --build         commit count (CFBundleVersion)
#        version.sh --full          human version, e.g. 0.2.1+3.gabc1234[.dirty]
#        version.sh --write         write Config/Version.xcconfig (gitignored; included by Base.xcconfig)
# Tagged commit = that tag's X.Y.Z. N commits past a tag = next patch (a dev build of the coming
# release); the +N.g<sha> suffix appears only in --full, never in the Apple version.
# VERSION_REPO overrides the repo to inspect (used by the tests).
set -euo pipefail

repo="${VERSION_REPO:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
g() { git -C "$repo" "$@"; }

desc="$(g describe --tags --long --match 'v[0-9]*.[0-9]*.[0-9]*' 2>/dev/null || true)"
count="$(g rev-list --count HEAD 2>/dev/null || echo 1)"
if [ -n "$desc" ]; then
  sha="${desc##*-g}"; rest="${desc%-g*}"; ahead="${rest##*-}"; tag="${rest%-*}"; tag="${tag#v}"
else
  tag="0.0.0"; ahead="$count"; sha="$(g rev-parse --short HEAD 2>/dev/null || echo unknown)"
fi
printf '%s' "$tag" | grep -qE '^[0-9]+\.[0-9]+\.[0-9]+$' || { echo "error: tag '$tag' is not numeric X.Y.Z" >&2; exit 1; }

IFS=. read -r maj min pat <<EOT
$tag
EOT
if [ "$ahead" = 0 ]; then
  marketing="$tag"; full="$tag"
else
  marketing="$maj.$min.$((pat + 1))"; full="$marketing+$ahead.g$sha"
fi
if [ -n "$(g status --porcelain --untracked-files=no 2>/dev/null)" ]; then full="$full.dirty"; fi

case "${1:-}" in
  "")          printf 'MARKETING_VERSION = %s\nCURRENT_PROJECT_VERSION = %s\n' "$marketing" "$count" ;;
  --marketing) printf '%s\n' "$marketing" ;;
  --build)     printf '%s\n' "$count" ;;
  --full)      printf '%s\n' "$full" ;;
  --write)     out="$repo/Config/Version.xcconfig"
               { echo "// Generated by scripts/version.sh --write from git tags. Gitignored; never hand-edit."
                 "$0" ; } > "$out" ;;
  *)           echo "usage: version.sh [--marketing | --build | --full | --write]" >&2; exit 2 ;;
esac
