#!/usr/bin/env bash
# Derive the app version from git tags vX.Y.Z (docs/versioning.md). Bash 3.2 compatible, standalone.
# Usage: version.sh                 xcconfig lines: MARKETING_VERSION, CURRENT_PROJECT_VERSION, GIT_COMMIT
#        version.sh --marketing     numeric x.y.z for Apple (CFBundleShortVersionString)
#        version.sh --build         commit count (CFBundleVersion)
#        version.sh --full          human version, e.g. 0.2.1+3.gabc1234[.dirty]
#        version.sh --commit        short sha, "-dirty" when tracked files have uncommitted changes
#        version.sh --tag           newest release tag reachable from HEAD (vX.Y.Z), empty when there is none
#        version.sh --write         write Config/Version.xcconfig (gitignored; included by Base.xcconfig)
# Release tag = the newest strict vX.Y.Z (no suffix) reachable from HEAD. HEAD on it = that X.Y.Z;
# N commits past it = the next patch (a dev build of the coming release); no tag at all = 0.0.1.
# The +N.g<sha> dev marker appears only in --full, never in the Apple version.
# Env: VERSION_REPO (repo to inspect, default this one), VERSION_OUT (file for --write, default Config/Version.xcconfig).
set -euo pipefail

repo="${VERSION_REPO:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
out="${VERSION_OUT:-$repo/Config/Version.xcconfig}"
g() { git -C "$repo" "$@"; }

if g rev-parse --verify -q HEAD >/dev/null 2>&1; then
  count="$(g rev-list --count HEAD)"; sha="$(g rev-parse --short=7 HEAD)"
  tag="$(g tag --merged HEAD --list 'v*' | grep -E '^v[0-9]+\.[0-9]+\.[0-9]+$' | sort -t. -k1.2,1n -k2,2n -k3,3n | tail -1 || true)"
  if [ "$(g rev-parse --is-shallow-repository 2>/dev/null)" = true ]; then
    echo "version.sh: warning: shallow clone, the build number counts only the fetched history ($count); fetch full history before archiving" >&2
  fi
else
  count=1; sha=unknown; tag=""
fi

if [ -n "$tag" ]; then
  ahead="$(g rev-list --count "$tag..HEAD")"; base="${tag#v}"
else
  ahead="$count"; base="0.0.0"
fi
IFS=. read -r maj min pat <<EOT
$base
EOT
if [ "$ahead" = 0 ]; then
  marketing="$base"; full="$base"
else
  marketing="$maj.$min.$((pat + 1))"; full="$marketing+$ahead.g$sha"
fi
commit="$sha"
if [ "$sha" != unknown ] && [ -n "$(g status --porcelain --untracked-files=no 2>/dev/null)" ]; then
  full="$full.dirty"; commit="$sha-dirty"
fi

lines() { printf 'MARKETING_VERSION = %s\nCURRENT_PROJECT_VERSION = %s\nGIT_COMMIT = %s\n' "$marketing" "$count" "$commit"; }

case "${1:-}" in
  "")          lines ;;
  --marketing) printf '%s\n' "$marketing" ;;
  --build)     printf '%s\n' "$count" ;;
  --full)      printf '%s\n' "$full" ;;
  --commit)    printf '%s\n' "$commit" ;;
  --tag)       printf '%s\n' "$tag" ;;
  --write)     body="// Generated by scripts/version.sh --write from git tags and the commit count. Gitignored; never hand-edit.
$(lines)"
               # Rewrite only on a change, so an unchanged version does not invalidate the Xcode build.
               if [ ! -f "$out" ] || [ "$(cat "$out")" != "$body" ]; then
                 mkdir -p "$(dirname "$out")"; printf '%s\n' "$body" > "$out.tmp" && mv "$out.tmp" "$out"
               fi ;;
  *)           echo "usage: version.sh [--marketing | --build | --full | --commit | --tag | --write]" >&2; exit 2 ;;
esac
