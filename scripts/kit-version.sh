#!/usr/bin/env bash
# Prints the version of the shared kit checkout the app is built against (X.Y.Z), read from the kit's own source of truth:
# `ParrotKitInfo.version` in Sources/ParrotKit/Version.swift (the kit's release script refuses a tag that differs from it).
# Usage: kit-version.sh [KIT_DIR]     KIT_DIR defaults to scripts/kit-dir.sh
#        kit-version.sh --write       write Config/Kit.xcconfig (gitignored; included by Base.xcconfig) with GREENFIELD_KIT_REQUIRED
# Env: KIT_OUT (file for --write, default Config/Kit.xcconfig).
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
write=0
if [ "${1:-}" = "--write" ]; then write=1; shift; fi
kit="${1:-$("$here/kit-dir.sh")}"
source_file="$kit/Sources/ParrotKit/Version.swift"
[ -f "$source_file" ] || { echo "kit-version: no $source_file" >&2; exit 1; }
version="$(sed -nE 's/^[[:space:]]*public static let version = "([0-9]+\.[0-9]+\.[0-9]+)".*/\1/p' "$source_file" | head -1)"
[ -n "$version" ] || { echo "kit-version: no ParrotKitInfo.version (X.Y.Z) in $source_file" >&2; exit 1; }
if [ "$write" = 1 ]; then
  out="${KIT_OUT:-$here/../Config/Kit.xcconfig}"
  tmp="$(mktemp)"
  printf '// Generated by scripts/kit-version.sh from the kit checkout; gitignored, never hand-edited.\nGREENFIELD_KIT_REQUIRED = %s\n' "$version" > "$tmp"
  if cmp -s "$tmp" "$out" 2>/dev/null; then rm -f "$tmp"; else mv "$tmp" "$out"; fi
else
  printf '%s\n' "$version"
fi
